-- 11/11/2026 — Parte B (Devoluções): tabelas do módulo. Todas com RLS ligado e sem
-- policies: só o servidor (service role) lê e escreve. Dados do comprador: só id e
-- nome de usuário da plataforma (nunca endereço, telefone ou CPF).
set statement_timeout = '5min';

create table if not exists public.devolucoes (
  id uuid primary key default gen_random_uuid(),
  loja_id uuid not null references public.lojas(id),
  canal text not null check (canal in ('shopee','tiktok')),
  plataforma_id text not null,              -- Shopee return_sn / TikTok return_id
  pedido_id text not null,                  -- order_sn / order_id
  tipo text not null default 'devolucao_reembolso'
    check (tipo in ('devolucao_reembolso','so_reembolso','troca','cancelamento')),
  status_plataforma text,
  etapa text not null default 'solicitado'
    check (etapa in ('solicitado','resposta','voltando','recebido','inspecao','decisao','encerrado')),
  motivo_codigo text,
  motivo_texto text,
  texto_comprador text,
  valor_pedido numeric,
  valor_reembolso_pedido numeric,
  valor_reembolsado numeric,
  prazo_resposta timestamptz,
  prazo_prova timestamptz,
  prazo_contestar timestamptz,
  prazo_oferta timestamptz,
  rastreio_reverso text,
  transportadora_reversa text,
  chegou_em timestamptz,
  comprador_id text,
  comprador_usuario text,
  sugestao jsonb,
  regra_id uuid,
  disputa_status text,
  compensacao_status text,
  valor_recuperado numeric,
  credito_esperado_ate date,
  credito_status text default 'nao_se_aplica'
    check (credito_status in ('aguardando','creditado','nao_creditado','nao_se_aplica')),
  credito_transacao_ref text,
  creditado_em timestamptz,
  resultado text
    check (resultado is null or resultado in ('aprovada','recusada','parcial','ganha','perdida','cancelada_comprador','vencida')),
  itens jsonb,                               -- [{sku, nome, quantidade, valor, imagem}]
  bruto jsonb,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  plataforma_criado_em timestamptz,
  plataforma_atualizado_em timestamptz,
  unique (canal, plataforma_id)
);
create index if not exists devolucoes_etapa_prazo_idx on public.devolucoes (etapa, prazo_resposta);
create index if not exists devolucoes_pedido_idx on public.devolucoes (pedido_id);
create index if not exists devolucoes_rastreio_idx on public.devolucoes (rastreio_reverso);
create index if not exists devolucoes_loja_etapa_idx on public.devolucoes (loja_id, etapa);
create index if not exists devolucoes_credito_idx on public.devolucoes (credito_status, credito_esperado_ate);
alter table public.devolucoes enable row level security;

create table if not exists public.devolucao_eventos (
  id bigint generated by default as identity primary key,
  devolucao_id uuid not null references public.devolucoes(id) on delete cascade,
  quando timestamptz not null default now(),
  origem text not null check (origem in ('plataforma','comprador','vendedor','assistente','sistema','equipe')),
  tipo text not null,
  descricao text,
  dados jsonb,
  usuario_id uuid,
  chave text                                  -- idempotência (ex.: tiktok:<event>:<ts>)
);
create index if not exists devolucao_eventos_dev_idx on public.devolucao_eventos (devolucao_id, quando);
create unique index if not exists devolucao_eventos_chave_idx on public.devolucao_eventos (devolucao_id, chave) where chave is not null;
alter table public.devolucao_eventos enable row level security;

create table if not exists public.devolucao_midias (
  id uuid primary key default gen_random_uuid(),
  devolucao_id uuid not null references public.devolucoes(id) on delete cascade,
  origem text not null check (origem in ('comprador','nos')),
  tipo text not null check (tipo in ('foto','video','quadro')),
  storage_path text,
  url_plataforma text,
  quadro_do_video uuid references public.devolucao_midias(id) on delete set null,
  segundo_no_video numeric,
  legenda text,
  enviado_em timestamptz,
  ref_plataforma text,
  criado_por uuid,
  criado_em timestamptz not null default now(),
  unique (devolucao_id, url_plataforma)
);
create index if not exists devolucao_midias_dev_idx on public.devolucao_midias (devolucao_id);
alter table public.devolucao_midias enable row level security;

create table if not exists public.devolucao_inspecoes (
  id uuid primary key default gen_random_uuid(),
  devolucao_id uuid not null references public.devolucoes(id) on delete cascade,
  peso_envio_kg numeric,
  peso_chegada_kg numeric,
  itens jsonb,
  estado text check (estado is null or estado in ('novo','usado','defeito','diferente_ou_faltando')),
  destino text check (destino is null or destino in ('estoque','saldo','avaria','contestacao')),
  observacao text,
  inspecionado_por uuid,
  inspecionado_em timestamptz,
  nfe_numero text,
  nfe_data date,
  ajuste_upseller_feito boolean not null default false,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists devolucao_inspecoes_dev_idx on public.devolucao_inspecoes (devolucao_id);
alter table public.devolucao_inspecoes enable row level security;

create table if not exists public.regras_devolucao (
  id uuid primary key default gen_random_uuid(),
  conta_id uuid,
  ordem integer not null default 100,
  ativa boolean not null default false,
  nome text not null,
  condicao jsonb not null default '{}'::jsonb,
  acao jsonb not null default '{}'::jsonb,
  modo text not null default 'sugerir' check (modo in ('sugerir','aprovar','automatico')),
  usos integer not null default 0,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
alter table public.regras_devolucao enable row level security;

create table if not exists public.devolucao_aprovacoes (
  id uuid primary key default gen_random_uuid(),
  devolucao_id uuid not null references public.devolucoes(id) on delete cascade,
  acao jsonb not null,
  pedida_em timestamptz not null default now(),
  via text not null default 'tela' check (via in ('telegram','tela')),
  telegram_message_id bigint,
  decisao text check (decisao is null or decisao in ('aprovada','editada','recusada')),
  decidido_por text,
  decidido_em timestamptz,
  executada_em timestamptz,
  resposta_api jsonb,
  erro text,
  idempotency_key uuid not null default gen_random_uuid()
);
create index if not exists devolucao_aprovacoes_dev_idx on public.devolucao_aprovacoes (devolucao_id, pedida_em desc);
alter table public.devolucao_aprovacoes enable row level security;

create table if not exists public.compradores_risco (
  canal text not null,
  comprador_id text not null,
  devolucoes_90d integer not null default 0,
  suspeito boolean not null default false,
  motivo text,
  atualizado_em timestamptz not null default now(),
  primary key (canal, comprador_id)
);
alter table public.compradores_risco enable row level security;

-- Bucket PRIVADO para fotos, vídeos e quadros (B0). Idempotente.
insert into storage.buckets (id, name, public, file_size_limit)
values ('devolucoes', 'devolucoes', false, 262144000)
on conflict (id) do nothing;

-- atualizado_em automático
create or replace function public.tg_atualizado_em() returns trigger language plpgsql as $$
begin new.atualizado_em = now(); return new; end $$;
drop trigger if exists devolucoes_atualizado on public.devolucoes;
create trigger devolucoes_atualizado before update on public.devolucoes for each row execute function public.tg_atualizado_em();
drop trigger if exists devolucao_inspecoes_atualizado on public.devolucao_inspecoes;
create trigger devolucao_inspecoes_atualizado before update on public.devolucao_inspecoes for each row execute function public.tg_atualizado_em();
